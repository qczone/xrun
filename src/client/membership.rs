//! User operations on network identity and membership.
use crate::{
    config::{self, Identity},
    error::ErrorCode,
    net,
    protocol::*,
};
use anyhow::{Result, bail};
use serde::{Deserialize, Serialize};
#[derive(Debug, Serialize)]
/// Saved single-device access policy after any running daemon acknowledged a reload.
pub struct Permission {
    /// Immutable source ID whose local access rule was changed.
    pub source_device_id: String,
    /// Whether this individual grant allows access; global pause and denials still apply.
    pub allowed: bool,
}
#[derive(Debug, Serialize)]
/// Saved registration, without daemon initialization or service startup.
pub struct JoinInfo {
    /// Immutable device ID of the saved registration.
    pub device_id: String,
    /// Device name recorded in the verified roster.
    pub name: String,
    /// Signed inviter policy recorded when the identity joined.
    pub registration: Registration,
    /// Network identifier derived from its root public key.
    pub network_id: String,
    /// Signed relay endpoints used by the saved identity.
    pub relay_addresses: Vec<String>,
}
/// Register with a one-use invitation and save its one-way grant to the manager.
/// Success does not start or initialize the daemon; failures retain a pending key for
/// safe retry. An already joined identity must remain in the same network.
pub async fn join(link: &str, name: Option<String>) -> Result<JoinInfo> {
    let dir = config::device_dir()?;
    let existing = config::network_dir_at(&dir)?.join("identity.toml").exists();
    let id = super::join_identity(link, name).await?;
    if !existing {
        config::update_permission(&crate::network::current(&id)?.roster.manager_id, false)?;
        crate::control::refresh_access().await?;
    }
    joined(id)
}
fn joined(id: Identity) -> Result<JoinInfo> {
    let network_id = crate::network::authority(&id)?.network_id.clone();
    Ok(JoinInfo {
        device_id: id.device_id,
        name: id.name,
        registration: id.registration,
        network_id,
        relay_addresses: id.addresses,
    })
}

/// Meaning of a validated connection link. Inspecting it performs no network IO.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum ConnectionKind {
    /// Create or resume a manager identity using a complete relay deployment link.
    Create,
    /// Register a member using an invitation issued by its manager.
    Join,
}

/// Validate and classify a deployment link or member invitation.
pub fn connection_kind(link: &str) -> Result<ConnectionKind> {
    let link = link.trim();
    crate::network::validate_connection_link(link)?;
    if link.starts_with("xrun://") {
        Ok(ConnectionKind::Join)
    } else {
        Ok(ConnectionKind::Create)
    }
}

/// Create or join a network with an explicit local rule for its verified manager.
/// The manager receives no reciprocal grant; false denies its access even when an
/// invitation contains an optional grant to the manager. Services are started
/// by the CLI or desktop adapter after this operation saves registration and policy.
pub async fn connect(link: &str, name: Option<String>, allow_manager: bool) -> Result<JoinInfo> {
    match connection_kind(link)? {
        ConnectionKind::Create => {
            if allow_manager {
                bail!(
                    ErrorCode::InvalidRequest.error("--allow-manager requires a member invitation")
                )
            }
            create_network(link.trim(), name).await
        }
        ConnectionKind::Join => {
            let id = super::join_identity(link.trim(), name).await?;
            // Trust the manager in the verified identity and roster, not an
            // unverified device ID taken from the pasted link. An unchecked
            // desktop consent must also override an invitation's optional grant.
            let roster = crate::network::current(&id)?;
            config::update_permission(&roster.roster.manager_id, allow_manager)?;
            crate::control::refresh_access().await?;
            joined(id)
        }
    }
}

/// Create and publish a manager identity. Success means registration is saved,
/// not that the daemon is initialized or running. Retryable publication failures
/// retain pending authority, and never create a second root on retry.
pub async fn create_network(link: &str, name: Option<String>) -> Result<JoinInfo> {
    joined(crate::network::create(link, name).await?)
}

/// A single-use, ten-minute invitation generated by the network manager.
#[derive(Debug, Serialize, Deserialize)]
pub struct Invitation {
    /// Secret bearer link; show or copy only after a successful request.
    pub link: String,
    /// Whether accepting the link grants the manager access to the joining device.
    pub allow: bool,
    /// Remaining validity in seconds at creation.
    pub expires_in: u64,
    /// Short-invitation identity used for explicit cancellation or replacement.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub invitation_id: Option<String>,
    /// Relay host and optional port.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub address: Option<String>,
    /// Human-readable, single-use eight-character code.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub code: Option<String>,
}

/// Generate an invitation after publishing the manager's current signed roster.
/// Requires the manager identity. `allow` lets the manager execute, transfer files and
/// capture screenshots on the joining device; it never grants access to the manager.
pub async fn invite(allow: bool) -> Result<Invitation> {
    invite_code(allow, None).await
}
/// Generate a short invitation in the running manager daemon, replacing one if requested.
pub async fn invite_code(allow: bool, replace: Option<&str>) -> Result<Invitation> {
    let id = Identity::load()?;
    crate::ipc::invite(&id, allow, replace).await
}
/// Cancel an unused short invitation in the running manager daemon.
pub async fn cancel_invitation(invitation: &str) -> Result<()> {
    crate::ipc::cancel_invitation(&Identity::load()?, invitation).await
}
/// Generate a self-contained invitation with a strong bearer token for automation.
pub async fn invite_link(allow: bool) -> Result<Invitation> {
    let mut id = Identity::load()?;
    net::renew_identity(&mut id).await?;
    Ok(serde_json::from_value(
        crate::network::invite(&id, allow).await?,
    )?)
}

/// Local revocation result, with independent remote delivery information.
#[derive(Debug, Serialize, Deserialize)]
pub struct Revocation {
    /// Immutable ID of the revoked member.
    pub device_id: String,
    /// The manager's signed roster has committed the revocation locally.
    pub revoked: bool,
    /// Version of the locally committed roster.
    pub roster_version: u64,
    /// Active remote members that did not confirm this version.
    pub undelivered: Vec<String>,
    /// Device discovery or synchronization failure after local commit, if any.
    pub sync_error: Option<String>,
}

/// Commit a member revocation and attempt delivery. Requires the manager identity;
/// its own identity cannot be revoked. A successful result remains locally effective
/// even when `sync_error` or `undelivered` is nonempty. Retry is idempotent and tries
/// delivery again; offline endpoints enforce revocation after receiving the roster.
pub async fn revoke(device: &str) -> Result<Revocation> {
    let mut id = Identity::load()?;
    net::renew_identity(&mut id).await?;
    Ok(serde_json::from_value(
        crate::network::revoke(&id, device).await?,
    )?)
}

/// Persist access for all current and future members, retaining individual grants
/// and denials, then wait for a running daemon to reload it. Denials take priority.
/// Reload errors do not roll back the already saved configuration.
pub async fn set_all_permissions(allow: bool) -> Result<()> {
    if allow {
        let id = Identity::load()?;
        crate::network::current(&id)?.require_bulk_access_target(&id.device_id)?;
    }
    config::update_all_permissions(allow)?;
    crate::control::refresh_access().await
}

/// Persist the remote-access pause and wait for a running daemon to reload it.
/// Permissions remain saved; pausing closes authorized peer sessions without
/// canceling accepted background jobs. Reload failure does not undo the saved pause.
pub async fn pause_access(paused: bool) -> Result<()> {
    config::pause_remote_access(paused)?;
    crate::control::refresh_access().await
}
/// Persist an allow or deny rule for an immutable ID or resolved member name, then
/// wait for a running daemon to reload it. IDs work while offline; names require a
/// verified roster. Reload errors leave the configuration saved. No job is canceled.
pub async fn set_permission(value: &str, allow: bool) -> Result<Permission> {
    let id = Identity::load()?;
    let id_value = value.to_ascii_lowercase();
    let device_id = if crate::protocol::valid_device_id(&id_value) {
        id_value
    } else {
        if !crate::protocol::valid_name(value) {
            bail!(
                ErrorCode::InvalidDeviceId
                    .error("expected a device name or a 32-digit hexadecimal device ID")
            );
        }
        let device: Device = net::http(
            &id,
            reqwest::Method::GET,
            &format!("/devices/{value}"),
            None,
        )
        .await?;
        device.device_id
    };
    config::update_permission(&device_id, allow)?;
    crate::control::refresh_access().await?;
    Ok(Permission {
        source_device_id: device_id,
        allowed: allow,
    })
}
